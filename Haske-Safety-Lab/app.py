import re
import streamlit as st
import joblib

MODEL_PATH = "results/linear_svm_sms_model_robustness_v1.joblib"

st.set_page_config(
    page_title="Haske Safety Lab",
    page_icon="🛡️",
    layout="centered"
)

@st.cache_resource
def load_model():
    return joblib.load(MODEL_PATH)

def check_warning_signs(text):
    """Transparent rule-based indicators; not a trained multi-label model."""
    t = text.lower()

    patterns = {
        "R1 — Unexpected prize or money": [
            r"\bwon\b", r"\bwinner\b", r"\bprize\b", r"\breward\b",
            r"\bgrant\b", r"\bfree money\b", r"\bclaim your"
        ],
        "R2 — Pressure to act fast": [
            r"\bimmediately\b", r"\burgent\b", r"\bact now\b",
            r"\bwithin \d+ minutes?\b", r"\bexpires today\b",
            r"\baccount.{0,25}blocked\b", r"\bfinal warning\b"
        ],
        "R3 — Request for secret details": [
            r"\botp\b", r"\bpin\b", r"\bpassword\b",
            r"\bverification code\b", r"\bsecret code\b"
        ],
        "R4 — Suspicious link": [
            r"https?://\S+", r"\bwww\.\S+", r"\bbit\.ly/\S+",
            r"\btinyurl\.com/\S+"
        ],
        "R5 — Bank or official impersonation": [
            r"\bbank\b", r"\bcentral bank\b", r"\bpolice\b",
            r"\bcustoms\b", r"\bgovernment\b", r"\baccount department\b"
        ],
    }

    return {
        name: any(re.search(pattern, t) for pattern in rules)
        for name, rules in patterns.items()
    }

st.title("🛡️ Haske Safety Lab")
st.subheader("SMS Scam Screening — English and Hausa")
st.write(
    "Enter a message to screen it for suspicious patterns and review "
    "possible warning signs."
)

st.info(
    "Privacy: Use fictional or anonymised examples. Never enter real "
    "passwords, PINs, OTPs, BVNs, NINs or banking details."
)

message = st.text_area(
    "SMS message",
    placeholder="Paste a message here...",
    height=150
)

if st.button("Screen message", type="primary"):
    if not message.strip():
        st.warning("Please enter a message first.")
    else:
        try:
            model = load_model()
            prediction = str(model.predict([message])[0]).lower()
            warnings = check_warning_signs(message)

            st.markdown("### Screening result")

            if prediction == "suspicious":
                st.warning(
                    "**Flagged for further review.** This does not prove "
                    "that the message is a scam."
                )
            else:
                st.success(
                    "**Not flagged by this model.** This does not guarantee "
                    "that the message is safe."
                )

            st.markdown("### Possible warning signs")
            st.caption(
                "These indicators are generated by simple text rules, "
                "not by a trained multi-label warning-sign model."
            )

            for name, found in warnings.items():
                if found:
                    st.write(f"⚠️ **{name}** — indicator detected")
                else:
                    st.write(f"Not detected: {name}")

            st.markdown("### What you should do")
            st.write(
                "Do not click unexpected links or share secret codes. "
                "Verify requests through an official contact method "
                "you obtain independently."
            )

        except Exception as exc:
            st.error(
                "The model could not process the message. "
                "Check the model path and installed dependencies."
            )
            st.caption(f"Technical detail: {type(exc).__name__}: {exc}")

st.divider()
st.caption(
    "Research prototype only. The model was trained on a public, "
    "English-heavy dataset and has not been validated sufficiently "
    "for dependable Hausa scam detection. A screening result is not "
    "a security guarantee."
)
